    private static void addText(StringBuilder sb, String font, int size, int x, int y, String text) {
        sb.append("BT ").append(font).append(" ").append(size).append(" Tf ").append(x).append(" ").append(y).append(" Td (").append(escapePdfText(text)).append(") Tj ET\n");
    }

    private static void addLine(StringBuilder sb, int x1, int y1, int x2, int y2, int width) {
        sb.append(width).append(" w ").append(x1).append(" ").append(y1).append(" m ").append(x2).append(" ").append(y2).append(" l S\n");
    }

    private static String escapePdfText(String text) {
        return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)");
    }
